// Assembles the feature probes (src/probes/*.wat) and writes them as a module
// for the page:  export const PROBES = [{name, title, wasm (base64)}, ...]
// The first line of each .wat, a ";;" comment, is its title.
//
//   node tools/probes.mjs <wasm-as> <probes.js> src/probes/*.wat
import { execFileSync } from 'node:child_process';
import { readFileSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { basename, join } from 'node:path';

const [wasmAs, out, ...files] = process.argv.slice(2);
const dir = mkdtempSync(join(tmpdir(), 'probes-'));
const probes = [];
try {
  for (const f of files) {
    const name = basename(f, '.wat');
    const title = readFileSync(f, 'utf8').split(/\r?\n/)[0].replace(/^;;\s*/, '');
    const wasm = join(dir, name + '.wasm');
    execFileSync(wasmAs, ['--all-features', f, '-o', wasm], { stdio: 'inherit' });
    probes.push({ name, title, wasm: readFileSync(wasm).toString('base64') });
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
writeFileSync(out, '// Generated by tools/probes.mjs from src/probes/*.wat. Do not edit.\n'
  + `export const PROBES = ${JSON.stringify(probes, null, 2)};\n`);
